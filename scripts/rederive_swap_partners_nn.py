#!/usr/bin/env python3
"""
rederive_swap_partners_nn.py
================================
Review concern #3 (major): e3_swap_partners.csv's partner for each
selected field is chosen, among all wet-fraction-matched candidates
(caliper 0.03, minimum 30-day gap), by MAXIMIZING the spectral
difference (raps_diff). That is a deliberate choice to make the swap
axis the "hardest" version of wrong conditioning, but it also means the
reported swap effect size could be substantially a property of that
maximization step rather than of "wrong conditioning" in general. How
much of the effect survives under a much less aggressive selection rule
-- plain nearest-neighbour by wet-fraction gap, no spectral-difference
step at all -- has not been checked.

THIS SCRIPT HAS TWO STAGES, because re-deriving partners is CPU-only but
computing new BPD values for the new partners needs the trained
checkpoint and GPU, so they cannot run in the same invocation.

STAGE A (--mode derive, the default; CPU-only, no GPU, no checkpoint):
  1. Loads e1_covariates.csv (field_id, wet_fraction, raps_log_slope,
     day_of_year or date, for every test day). If it's missing, it is
     regenerated by importing scripts/compute_e1_covariates.py's own
     functions directly (same logic, not a reimplementation) from the
     raw h5, so this script is self-contained either way.
  2. Reconstructs, for each selected field, the SAME candidate pool
     e3_swap_partners.csv used (wet-fraction caliper 0.03, minimum
     30-day gap, excluding the field itself), and CROSS-CHECKS the
     reconstructed candidate COUNT against e3_swap_partners.csv's own
     n_candidates column before trusting anything downstream -- if
     these disagree, this script's caliper/day-gap logic does not
     actually match the original pipeline and the new partners would
     not be a fair comparison.
  3. From that SAME candidate pool, selects the NEAREST-NEIGHBOUR
     partner by wet-fraction gap (minimizing |wf_gap|, breaking ties by
     smallest day_gap), instead of maximizing raps_diff.
  4. Writes e3_swap_partners_nearest_neighbor.csv in the exact schema
     scripts/e3_conditioning_sensitivity.py's --partners-csv argument
     already expects, so no changes to that script are needed.

STAGE B (--mode compare; CPU-only; run AFTER you have used the new CSV
with the real model):
    python scripts/e3_conditioning_sensitivity.py \\
        --partners-csv e3_swap_partners_nearest_neighbor.csv \\
        --out-dir e3_outputs_nn_swap
  then:
    python rederive_swap_partners_nn.py --mode compare \\
        --original-results e3_results_FINAL_corrected.jsonl \\
        --nn-results e3_outputs_nn_swap/e3_results.jsonl
  reports the per-field swap effect (BPD_swap - BPD_baseline) under
  BOTH partner-selection rules, field-bootstrap CIs for each, and their
  paired difference, using the same iid-over-fields bootstrap
  analyze_e3_conditioning_sensitivity.py already uses (this is a
  cross-sectional 20-field sample, not a time series).

USAGE
-----
    python rederive_swap_partners_nn.py --mode derive
    python rederive_swap_partners_nn.py --mode derive --covariates e1_covariates.csv
    python rederive_swap_partners_nn.py --mode compare \\
        --original-results e3_results_FINAL_corrected.jsonl \\
        --nn-results e3_outputs_nn_swap/e3_results.jsonl
"""
from __future__ import annotations

import os
import argparse
import importlib.util
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))
from _review_common import field_bootstrap_dist, percentile_ci  # noqa: E402

CALIPER = 0.03
MIN_DAY_GAP = 30
MSWX_TEST_H5 = os.environ.get("MSWX_TEST_H5", "data/mswx_test_2011-2014.h5")
def load_or_build_covariates(covariates_path: Path, h5_path: str) -> pd.DataFrame:
    if covariates_path.exists():
        print(f"Loading {covariates_path}")
        return pd.read_csv(covariates_path)

    print(f"[warn] {covariates_path} not found; regenerating it directly from {h5_path} "
          f"using scripts/compute_e1_covariates.py's own functions (not a reimplementation).")
    script_path = REPO_ROOT / "scripts" / "compute_e1_covariates.py"
    if not script_path.exists():
        raise FileNotFoundError(
            f"Need either {covariates_path} or {script_path} to proceed.")
    spec = importlib.util.spec_from_file_location("compute_e1_covariates", script_path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    import h5py
    with h5py.File(h5_path, "r") as f:
        precip = f["precipitation"][:]
    n_total = precip.shape[0]
    dates = pd.date_range("2011-01-01", periods=n_total, freq="D")
    rows = []
    for i in range(n_total):
        row = {"field_id": i, **mod.compute_covariates_for_field(precip[i], dates[i])}
        rows.append(row)
        if (i + 1) % 200 == 0:
            print(f"  covariates [{i + 1}/{n_total}]", flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(covariates_path, index=False)
    print(f"Wrote {covariates_path}")
    return df


def candidate_pool(cov: pd.DataFrame, field_id: int) -> pd.DataFrame:
    row = cov[cov["field_id"] == field_id].iloc[0]
    wf = row["wet_fraction"]
    cand = cov[(cov["field_id"] != field_id) &
                ((cov["wet_fraction"] - wf).abs() <= CALIPER) &
                ((cov["field_id"] - field_id).abs() >= MIN_DAY_GAP)].copy()
    cand["wf_gap"] = (cand["wet_fraction"] - wf).abs()
    cand["day_gap"] = cand["field_id"] - field_id
    if "raps_log_slope" in cov.columns:
        cand["raps_diff"] = (cand["raps_log_slope"] - row["raps_log_slope"]).abs()
    else:
        cand["raps_diff"] = float("nan")
    return cand


def derive(args):
    cov = load_or_build_covariates(args.covariates, args.h5)
    if not args.fields_csv.exists():
        print(f"error: {args.fields_csv} not found")
        return 1
    fields_df = pd.read_csv(args.fields_csv)
    field_ids = fields_df["field_id"].astype(int).tolist()

    original = None
    if args.original_partners.exists():
        original = pd.read_csv(args.original_partners).set_index("field_id")

    rows = []
    cross_check_mismatches = 0
    same_partner_count = 0
    for fid in field_ids:
        cand = candidate_pool(cov, fid)
        n_cand = len(cand)

        if original is not None and fid in original.index:
            orig_n = int(original.loc[fid, "n_candidates"])
            if orig_n != n_cand:
                cross_check_mismatches += 1
                print(f"  [warn] field {fid}: reconstructed n_candidates={n_cand} != "
                      f"original n_candidates={orig_n} -- caliper/day-gap logic may not "
                      f"exactly match the original selection; treat this field's NN "
                      f"partner with extra caution")

        if n_cand == 0:
            print(f"  [warn] field {fid}: no candidates under caliper={CALIPER}, "
                  f"min_day_gap={MIN_DAY_GAP}; skipping")
            continue

        cand["_day_gap_abs"] = cand["day_gap"].abs()
        nn_row = cand.sort_values(["wf_gap", "_day_gap_abs"]).iloc[0]
        nn_partner = int(nn_row["field_id"])

        orig_partner = int(original.loc[fid, "partner_id"]) if (original is not None and
                                                                   fid in original.index) else None
        if orig_partner is not None and orig_partner == nn_partner:
            same_partner_count += 1

        rows.append({"field_id": fid, "partner_id": nn_partner,
                      "wf_gap": float(nn_row["wf_gap"]), "day_gap": int(nn_row["day_gap"]),
                      "raps_diff": float(nn_row["raps_diff"]), "n_candidates": n_cand,
                      "original_partner_id": orig_partner,
                      "original_raps_diff": float(original.loc[fid, "raps_diff"])
                      if orig_partner is not None else float("nan")})

    out_df = pd.DataFrame(rows)
    print()
    print("=" * 100)
    print("NEAREST-NEIGHBOUR (by wet-fraction gap) PARTNERS, vs. ORIGINAL "
          "(max spectral-difference) PARTNERS")
    print("=" * 100)
    print(out_df[["field_id", "partner_id", "wf_gap", "day_gap", "raps_diff", "n_candidates",
                   "original_partner_id", "original_raps_diff"]]
          .to_string(index=False, float_format=lambda v: f"{v:.4f}"))

    if cross_check_mismatches:
        print(f"\n[warn] {cross_check_mismatches}/{len(field_ids)} fields' candidate counts "
              f"did not match e3_swap_partners.csv's own n_candidates. Numbers for those "
              f"fields are still written out below, but double-check this script's CALIPER "
              f"({CALIPER}) and MIN_DAY_GAP ({MIN_DAY_GAP}) constants against whatever the "
              f"original partner-selection script actually used if this count is large.")
    if original is not None:
        print(f"\n{same_partner_count}/{len(field_ids)} fields get the SAME partner under "
              f"both selection rules (their raps_diff was already close to the "
              f"wet-fraction-nearest candidate's).")

    # write in the EXACT schema e3_conditioning_sensitivity.py's --partners-csv expects
    out_cols = ["field_id", "partner_id", "wf_gap", "day_gap", "raps_diff", "n_candidates"]
    out_df[out_cols].to_csv(args.out_csv, index=False)
    print(f"\nWrote {args.out_csv}  (schema matches e3_swap_partners.csv exactly)")
    print(f"\nNext: python scripts/e3_conditioning_sensitivity.py --partners-csv {args.out_csv} "
          f"--out-dir e3_outputs_nn_swap")
    print(f"Then: python {Path(__file__).name} --mode compare --nn-results "
          f"e3_outputs_nn_swap/e3_results.jsonl")
    return 0


def load_results(path: Path) -> list[dict]:
    rows = []
    with open(path) as fh:
        for line in fh:
            line = line.strip()
            if line:
                rows.append(json.loads(line))
    return rows


def swap_diff_per_field(rows: list[dict]) -> dict:
    baseline = defaultdict(dict)
    swap = defaultdict(dict)
    for r in rows:
        if r["axis"] == "baseline":
            baseline[r["field_id"]][r["replicate"]] = r["bits_per_interior_dim"]
        elif r["axis"] == "swap":
            swap[r["field_id"]][r["replicate"]] = r["bits_per_interior_dim"]
    out = {}
    for fid in swap:
        diffs = [swap[fid][rep] - baseline[fid][rep] for rep in swap[fid] if rep in baseline[fid]]
        if diffs:
            out[fid] = float(np.mean(diffs))
    return out


def compare(args):
    if not args.original_results.exists():
        print(f"error: {args.original_results} not found")
        return 1
    if not args.nn_results.exists():
        print(f"error: {args.nn_results} not found. Run Stage A, then "
              f"scripts/e3_conditioning_sensitivity.py with the new partners CSV, first.")
        return 1

    orig_rows = load_results(args.original_results)
    nn_rows = load_results(args.nn_results)

    orig_diff = swap_diff_per_field(orig_rows)
    nn_diff = swap_diff_per_field(nn_rows)
    common = sorted(set(orig_diff) & set(nn_diff))
    if len(common) < len(orig_diff) or len(common) < len(nn_diff):
        print(f"[warn] comparing on {len(common)} fields present in BOTH result files "
              f"({len(orig_diff)} in original, {len(nn_diff)} in nn); the rest are dropped.")

    rng = np.random.default_rng(args.seed)
    orig_vals = np.array([orig_diff[f] for f in common])
    nn_vals = np.array([nn_diff[f] for f in common])
    paired_diff = orig_vals - nn_vals  # how much LARGER the original (max-spectral) effect is

    def summarize(name, vals):
        boot = field_bootstrap_dist(vals, args.n_boot, rng)
        lo, hi = percentile_ci(boot)
        print(f"  {name:>55}: mean={vals.mean():+.4f}  95% CI [{lo:+.4f}, {hi:+.4f}]  "
              f"(n_fields={len(vals)})")

    print("=" * 100)
    print("SWAP EFFECT SIZE: max-spectral-difference partner vs. nearest-neighbour partner")
    print("=" * 100)
    summarize("ORIGINAL (max spectral-difference) swap effect", orig_vals)
    summarize("NEAREST-NEIGHBOUR (wet-fraction only) swap effect", nn_vals)
    summarize("PAIRED DIFFERENCE (original - NN, per field)", paired_diff)
    frac_smaller = float(np.mean(nn_vals < orig_vals))
    print(f"\n  Fraction of fields where the NN-partner effect is SMALLER than the "
          f"original: {frac_smaller:.2f}")
    print()
    print("READING GUIDE: if the NN swap effect retains most of the original effect's")
    print("magnitude and its own CI still excludes zero, the swap finding is not an")
    print("artifact of maximizing spectral difference specifically -- plain wrong-day")
    print("conditioning already does most of the work. If the NN effect shrinks toward")
    print("zero (or its CI now includes zero), report the swap finding as specific to the")
    print("deliberately-adversarial selection, not evidence of general wrong-conditioning")
    print("sensitivity.")
    return 0


def main():
    p = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--mode", choices=["derive", "compare"], default="derive")
    p.add_argument("--covariates", type=Path, default=Path("e1_covariates.csv"))
    p.add_argument("--h5", type=str, default=MSWX_TEST_H5)
    p.add_argument("--fields-csv", type=Path, default=Path("e3_selected_fields.csv"))
    p.add_argument("--original-partners", type=Path, default=Path("e3_swap_partners.csv"))
    p.add_argument("--out-csv", type=Path, default=Path("e3_swap_partners_nearest_neighbor.csv"))
    p.add_argument("--original-results", type=Path,
                   default=Path("e3_results_FINAL_corrected.jsonl"))
    p.add_argument("--nn-results", type=Path,
                   default=Path("e3_outputs_nn_swap/e3_results.jsonl"))
    p.add_argument("--n-boot", type=int, default=2000)
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()

    if args.mode == "derive":
        return derive(args)
    return compare(args)


if __name__ == "__main__":
    raise SystemExit(main())
